def normalize_stars(stars):
  if not stars:
    return []
  mean_x = sum(p[0] for p in stars) / len(stars)
  mean_y = sum(p[1] for p in stars) / len(stars)
  shifted = [(x - mean_x, y - mean_y) for x, y in stars]
  max_dist = max(math.hypot(x, y) for x, y in shifted)
  if max_dist == 0:
    return shifted
  return [(x / max_dist, y / max_dist) for x, y in shifted]


def predict_constellation(user_stars):
  if not user_stars:
    return None, float("inf")

  user_norm = normalize_stars(user_stars)
  best_match = None
  min_error = float("inf")

  for name, db_coords in constellation_db.items():
    db_norm = normalize_stars(db_coords)

    total_dist = 0
    for u in user_norm:
      closest_dist = min(math.hypot(u[0] - d[0], u[1] - d[1]) for d in db_norm)
      total_dist += closest_dist

    avg_error = total_dist / len(user_norm)

    if avg_error < min_error:
      min_error = avg_error
      best_match = name

  return best_match, min_error


